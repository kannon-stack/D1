#!/usr/bin/env node
// Generates src/content/copy.ts from studio/content/copy.md (every ```yaml block, keyed by its
// "## section" heading). Run from the site folder after copy.md changes, then re-run
// scripts/subset-fonts.mjs in case the copy added a character:
//
//   node scripts/gen-copy.mjs
//
// Uses the `yaml` package bundled with the studio tools (no dependency added to the site).
// `hero.headline_options` is dropped: only the final `hero.headline` ships (decisions #17).
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const site = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const md = fs.readFileSync(path.join(site, "../studio/content/copy.md"), "utf8");
const require = createRequire(path.join(site, "../../../.claude/studio-tools/package.json"));
const YAML = require("yaml");

const copy = {};
let section = null;
const lines = md.split("\n");
for (let i = 0; i < lines.length; i++) {
  const h = lines[i].match(/^##\s+`?([\w-]+)`?\s*$/);
  if (h) section = h[1];
  if (lines[i].trim() === "```yaml" && section) {
    const body = [];
    for (i++; lines[i].trim() !== "```"; i++) body.push(lines[i]);
    copy[section] = { ...(copy[section] ?? {}), ...YAML.parse(body.join("\n")) };
  }
}
delete copy.hero?.headline_options;
for (const k of ["microcopy", "hero", "build", "process", "contact", "footer"]) {
  if (!copy[k]) throw new Error(`copy.md has no yaml block for "${k}"`);
}

const out = `// GENERATED by scripts/gen-copy.mjs from studio/content/copy.md. Do not edit by hand.
// Every user-facing string on the page comes from here.
export const copy = ${JSON.stringify(copy, null, 2)} as const;

export type Copy = typeof copy;
`;
fs.writeFileSync(path.join(site, "src/content/copy.ts"), out);
console.log("wrote src/content/copy.ts:", Object.keys(copy).join(", "));
