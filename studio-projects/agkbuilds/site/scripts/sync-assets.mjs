#!/usr/bin/env node
// Copies the Designer's drawings (studio/design/assets) into the site. Run from the site folder
// whenever drawing.mjs is re-run:
//
//   node scripts/sync-assets.mjs
//
// - hero-construction.svg, process-plate.svg, balloon.svg → src/assets/drawings.ts (string
//   exports, inlined by server components, so they follow the colour tokens and add no JS);
// - process-step-{1..4}.svg → public/drawings/ (mobile <img> thumbnails, own light/dark colours);
// - icon.svg → src/app/icon.svg.
//
// Fix applied to the thumbnails: drawing.mjs writes some <g> tags with two `class` attributes
// (e.g. `class="pl-layer" class="s-draft"`), which is an XML error, so a browser shows a broken
// image for the whole file. The copies here merge them into one attribute. Reported to the
// Director; remove this step once drawing.mjs is fixed.
import fs from "node:fs";
import path from "node:path";

const site = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const assets = path.join(site, "../studio/design/assets");
const read = (f) => fs.readFileSync(path.join(assets, f), "utf8").trim();

function mergeDuplicateClasses(svg) {
  return svg.replace(/<([a-zA-Z]+)((?:\s+[\w:-]+="[^"]*")*)\s*(\/?)>/g, (tag, name, attrs, selfClose) => {
    const classes = [...attrs.matchAll(/\sclass="([^"]*)"/g)].map((m) => m[1]);
    if (classes.length < 2) return tag;
    const rest = attrs.replace(/\sclass="[^"]*"/g, "");
    return `<${name} class="${classes.join(" ")}"${rest}${selfClose ? "/" : ""}>`;
  });
}

fs.mkdirSync(path.join(site, "src/assets"), { recursive: true });
fs.mkdirSync(path.join(site, "public/drawings"), { recursive: true });

const inline = {
  heroConstruction: read("hero-construction.svg"),
  processPlate: read("process-plate.svg"),
  balloon: read("balloon.svg"),
};
const ts =
  "// GENERATED by scripts/sync-assets.mjs from studio/design/assets. Do not edit by hand.\n" +
  Object.entries(inline)
    .map(([k, v]) => `export const ${k} = ${JSON.stringify(v)};`)
    .join("\n") +
  "\n";
fs.writeFileSync(path.join(site, "src/assets/drawings.ts"), ts);

for (let n = 1; n <= 4; n++) {
  const f = `process-step-${n}.svg`;
  const fixed = mergeDuplicateClasses(read(f));
  if (/<[^>]*\sclass="[^"]*"[^>]*\sclass="/.test(fixed)) throw new Error(`${f}: duplicate class remains`);
  fs.writeFileSync(path.join(site, "public/drawings", f), fixed + "\n");
}
fs.copyFileSync(path.join(assets, "icon.svg"), path.join(site, "src/app/icon.svg"));
console.log("synced drawings.ts, public/drawings/process-step-{1..4}.svg, app/icon.svg");
